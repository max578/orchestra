// Generate src/data/a0_results.ts from the study's binding table
// (src/data/a0_poster_numbers.csv, a verbatim copy of
// ORCHESTRA_dev/studies/A0/output/poster_numbers.csv written by
// studies/A0/08_poster_figure.R). Every number the A0 page shows is read from
// here; none is typed in a page. Run: node scripts/a0_results.mjs
import { readFileSync, writeFileSync } from "node:fs";
// The causal layer's numbers (src/data/a0_causal_numbers.csv, a verbatim copy of
// ORCHESTRA_dev/studies/A0/output/causal_numbers.csv, written by 09_causal_layer.R) are appended.
const read = (f) => {
  const [head, ...rows] = readFileSync(new URL(`../src/data/${f}`, import.meta.url), "utf8").trim().split("\n");
  if (head !== "name,value,source") throw new Error(`unexpected header in ${f}: ${head}`);
  return rows;
};
const rows = [...read("a0_poster_numbers.csv"), ...read("a0_causal_numbers.csv")];
const entries = rows.map((r) => { const [name, value, ...src] = r.split(","); return { name, value: Number(value), source: src.join(",") }; });
for (const e of entries) if (!Number.isFinite(e.value)) throw new Error("non-numeric value for " + e.name);
const lines = [
  "// GENERATED by scripts/a0_results.mjs from src/data/a0_poster_numbers.csv -- do not edit.",
  "// Source of truth: ORCHESTRA_dev/studies/A0/output/poster_numbers.csv (08_poster_figure.R, Study A0 v0.2, 2026-08-26)",
  "// and causal_numbers.csv (09_causal_layer.R, 2026-10-02).",
  "export const a0 = {",
  ...entries.map((e) => `  ${e.name}: ${e.value}, // ${e.source}`),
  "} as const;",
  "export const a0Sources = {",
  ...entries.map((e) => `  ${e.name}: ${JSON.stringify(e.source)},`),
  "} as const;",
  "",
];
writeFileSync(new URL("../src/data/a0_results.ts", import.meta.url), lines.join("\n"));
console.log(`a0_results.ts: ${entries.length} numbers`);
